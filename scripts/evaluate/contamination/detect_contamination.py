def _drop_numeric(toks: list[str], hashes: list[int], n: int) -> list[int | None]:
    """Blank out n-grams whose tokens are all numeric, keeping positions aligned."""
    return [
        None if all(t.isdigit() for t in toks[i : i + n]) else h
        for i, h in enumerate(hashes)
    ]


@dataclass
class EvalItem:
    benchmark: str
    item_id: str
    prompt: str
    core: str
    n_tokens: int
    n_long: int   # number of 13-gram positions
    n_short: int  # number of 8-gram positions


class EvalIndex:
    """Inverted index over the eval prompts: the small side of the comparison."""

    def __init__(self, items: list[EvalItem], hasher: MinHasher):
        self.items = items
        self.hasher = hasher
        self.exact: dict[int, list[int]] = collections.defaultdict(list)
        self.long: dict[int, list[tuple[int, int]]] = collections.defaultdict(list)
        self.short: dict[int, list[tuple[int, int]]] = collections.defaultdict(list)
        self.buckets: dict[int, list[int]] = collections.defaultdict(list)
        self.signatures: list[np.ndarray | None] = []

        # First pass: hash every item, and count in how many distinct items each
        # n-gram occurs so template phrasing can be identified and dropped.
        per_item: list[tuple[list[int], list[int]]] = []
        df_long: collections.Counter = collections.Counter()
        df_short: collections.Counter = collections.Counter()
        for item in items:
            toks = tokens(item.core)
            # All-numeric n-grams carry no linguistic content: sample grids and
            # I/O tables collide across unrelated problems. livecodebench/abc327_c
            # ("verify a 9x9 grid") shared 424 13-grams with an unrelated Aizu
            # Sudoku *solver* purely through digit rows, at MinHash Jaccard 0.0.
            # A genuinely duplicated problem always shares prose too, so dropping
            # these removes the false-positive class without masking real hits.
            longs = _drop_numeric(toks, ngram_hashes(toks, N_LONG), N_LONG)
            shorts = _drop_numeric(toks, ngram_hashes(toks, N_SHORT), N_SHORT)
            per_item.append((longs, shorts))
            df_long.update({h for h in longs if h is not None})
            df_short.update({h for h in shorts if h is not None})

        self.boilerplate_long = {h for h, c in df_long.items() if c >= BOILERPLATE_MIN_ITEMS}
        self.boilerplate_short = {h for h, c in df_short.items() if c >= BOILERPLATE_MIN_ITEMS}

        for idx, item in enumerate(items):
            toks = tokens(item.core)
            longs, shorts = per_item[idx]
            self.exact[exact_key(item.core)].append(idx)
            # Keep the position numbering of the FULL token stream so that
            # consecutive-position runs still mean "contiguous in the original
            # text"; only the boilerplate positions are omitted.
            n_long_eff = n_short_eff = 0
            for pos, h in enumerate(longs):
                if h is None or h in self.boilerplate_long:
                    continue
                self.long[h].append((idx, pos))
                n_long_eff += 1
            for pos, h in enumerate(shorts):
                if h is None or h in self.boilerplate_short:
                    continue
                self.short[h].append((idx, pos))
                n_short_eff += 1
            # Denominators over problem-specific content only.
            item.n_long = n_long_eff
            item.n_short = n_short_eff

            signature = hasher.signature(hasher.shingles(toks))
            self.signatures.append(signature)
            if signature is not None:
                for key in hasher.band_keys(signature):
                    self.buckets[key].append(idx)

        # Plain dicts pickle/fork more cheaply and avoid accidental key growth.
        self.exact = dict(self.exact)
        self.long = dict(self.long)
        self.short = dict(self.short)
        self.buckets = dict(self.buckets)


def load_eval_items(data_dir: Path, benchmarks: set[str] | None) -> list[EvalItem]:
    items: list[EvalItem] = []
    for path in sorted(data_dir.glob("*.jsonl")):
        name = path.stem
        if benchmarks and name not in benchmarks:
            continue
        with path.open() as handle:
            for line_no, line in enumerate(handle):
                line = line.strip()
                if not line:
                    continue
                row = json.loads(line)
                prompt = row.get("prompt") or ""
                if not prompt:
                    continue
                core = eval_core(prompt)
                toks = tokens(core)
                items.append(
                    EvalItem(
                        benchmark=row.get("benchmark", name),
                        item_id=str(row.get("id", line_no)),
                        prompt=prompt,
                        core=core,
                        n_tokens=len(toks),
                        n_long=max(0, len(toks) - N_LONG + 1),
                        n_short=max(0, len(toks) - N_SHORT + 1),
                    )
                )
    return items


