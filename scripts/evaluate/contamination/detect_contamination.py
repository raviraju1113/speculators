#!/usr/bin/env python3
"""Scan the EAGLE3 training corpora for overlap with the eval benchmarks.

Why this matters for a *speculator* specifically: the draft is trained to predict
the target's next tokens, and the training corpus's assistant turns were
regenerated by the same target the eval scores acceptance against, with eval
running greedy (``temperature: 0.0``). An eval prompt present in training means
the draft memorized exactly the continuation being measured, which inflates
``accept_rate``/``accept_length`` directly. Task accuracy is not the metric at
risk here; acceptance is.

Four detectors, cheapest/strictest first (see ``contamination_lib`` for the
template-stripping step every one of them depends on):

  exact      normalized token-stream hash                 -- zero false positives
  ngram13    fraction of the eval item's 13-grams found    -- GPT-3/Llama standard
  run        longest verbatim token run found              -- the readable number
  minhash    est. Jaccard vs the nearest training doc      -- catches restatements

The eval side is tiny (~3.5k prompts), so the index is built there and the
corpora are streamed once, in parallel, checking every training n-gram against
it. Memory stays flat regardless of corpus size.

Assistant turns are scanned too (``ngram13_resp``): an eval problem quoted inside
a training *response* is a weaker leak than a prompt match, but still means the
draft trained on target tokens for that problem.

Usage:
    python detect_contamination.py                       # all corpora, all benchmarks
    python detect_contamination.py --workers 64
    python detect_contamination.py --limit-rows 20000    # smoke test
    python detect_contamination.py --sources kimi,nemotron_math

Outputs (into --output-dir, default ./out):
    contamination_report.json   per-benchmark summary + thresholds
    contamination_report.md     the human-readable version
    eval_item_scores.jsonl      every eval item with all four scores
    review_pairs.jsonl          flagged items + matching training text, for tier-4
                                manual adjudication
"""

