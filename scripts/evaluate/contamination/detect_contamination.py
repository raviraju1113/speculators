N_LONG = 13  # primary n-gram order (GPT-3 / Llama convention)
N_SHORT = 8  # fallback for eval items too short to yield 13-grams

# Flag thresholds. These select *candidates for review*, they are not verdicts;
# tier 4 (review_pairs.jsonl) is where a candidate becomes a finding.
THRESHOLDS = {
    "run_dirty": 25,       # >=25 verbatim tokens in a row is not coincidence
    "run_suspect": N_LONG, # any 13-gram hit at all
    "ngram13_dirty": 0.20, # Llama-style 20% containment
    # A rephrased copy breaks long runs: aime/61 is present verbatim in
    # nemotron_math but written \(ABC\) instead of $ABC$ with the point renamed
    # D -> P, which caps 13-gram containment at 0.26. The shorter order survives
    # that kind of edit, so it carries the recall for paraphrased math items.
    "ngram8_dirty": 0.50,
    "minhash_dirty": 0.70,
    "minhash_suspect": 0.50,
}

# Per-document bar for keeping a training excerpt as reviewable evidence. Set
# well below the dirty bar: an item can clear `dirty` on containment pooled over
# several documents while no single document is itself striking, and a flagged
# item with no evidence attached cannot be adjudicated at tier 4.
EVIDENCE_MIN_13GRAMS = 4

# Containment is a ratio, so it is meaningless when the denominator is tiny: a
# 9-token mbpp prompt has just two 8-gram positions, and matching one of them on
# generic phrasing ("write a python function to ...") yields c8 = 0.50 by pure
# chance. Require this many n-gram positions before a containment ratio may flag
# an item. Below it, only exact match / long verbatim run / MinHash can flag --
# which for a 10-token prompt is exactly the right standard.
MIN_NGRAM_POSITIONS = 10

# An n-gram occurring in this many DISTINCT eval items is template phrasing, not
# problem content -- e.g. AIME's "...where m and n are relatively prime positive
# integers. Find m+n." or LiveCodeBench's "The first line contains a single
# integer t, the number of test cases". Such n-grams match training text
# constantly and produce long spurious runs (aime/65's entire 40-token "run" was
# the AIME answer-format sentence, with none of its actual problem in training).
# They are excluded from both the hit sets and the containment denominators, so
# every score below is computed over problem-specific content only.
BOILERPLATE_MIN_ITEMS = 5

CHUNK_BYTES = 64 << 20

# Populated in the parent before fork; workers inherit copy-on-write.
_IDX: "EvalIndex | None" = None


