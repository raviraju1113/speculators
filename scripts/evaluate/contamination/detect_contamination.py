def _turns(row: dict) -> list[tuple[str, str]]:
    """Yield (role, text) with `from`/`value` and `role`/`content` both handled."""
    convo = row.get("conversations") or row.get("messages") or []
    out = []
    for turn in convo:
        if not isinstance(turn, dict):
            continue
        role = turn.get("from") or turn.get("role") or ""
        text = turn.get("value") or turn.get("content") or ""
        if isinstance(text, str) and text:
            out.append((role.lower(), text))
    return out


def _iter_chunk(path: str, start: int, end: int):
    """Yield rows whose starting byte falls in [start, end), respecting lines."""
    with open(path, "rb") as handle:
        if start:
            handle.seek(start - 1)
            handle.readline()  # discard the partial line owned by the prior chunk
        else:
            handle.seek(0)
        while handle.tell() < end:
            raw = handle.readline()
            if not raw:
                return
            raw = raw.strip()
            if not raw:
                continue
            try:
                yield json.loads(raw)
            except json.JSONDecodeError:
                continue


def _scan_chunk(task: tuple[str, str, int, int, int, int]) -> dict:
    """Worker: match one byte-range of one corpus file against the eval index."""
    split, path, start, end, limit_rows, evidence_cap = task
    idx = _IDX
    assert idx is not None
    hasher = idx.hasher

    hits_long: set[tuple[int, int]] = set()
    hits_short: set[tuple[int, int]] = set()
    hits_resp: set[tuple[int, int]] = set()
    exact_hits: dict[int, list[str]] = collections.defaultdict(list)
    best_jaccard: dict[int, float] = {}
    evidence: dict[int, list[dict]] = collections.defaultdict(list)
    rows = 0

    for row in _iter_chunk(path, start, end):
        rows += 1
        if limit_rows and rows > limit_rows:
            break

        turns = _turns(row)
        prompt_text = "\n".join(t for role, t in turns if role in ("human", "user"))
        resp_text = "\n".join(
            t for role, t in turns if role in ("gpt", "assistant", "model")
        )
        if not prompt_text:
            continue

        doc_id = str(row.get("id", ""))
        core = train_core(prompt_text)
        toks = tokens(core)

        # --- tier 1: exact -------------------------------------------------
        matched = idx.exact.get(exact_key(core))
        if matched:
            for item_idx in matched:
                exact_hits[item_idx].append(doc_id)

        # --- tier 2: n-gram containment (prompt side) ----------------------
        per_doc: dict[int, int] = collections.Counter()
        for h in ngram_hashes(toks, N_LONG):
            for pair in idx.long.get(h, ()):
                hits_long.add(pair)
                per_doc[pair[0]] += 1
        for h in ngram_hashes(toks, N_SHORT):
            for pair in idx.short.get(h, ()):
                hits_short.add(pair)

        # --- tier 3: MinHash near-duplicate --------------------------------
        signature = hasher.signature(hasher.shingles(toks))
        doc_jaccard: dict[int, float] = {}
        if signature is not None:
            candidates = set()
            for key in hasher.band_keys(signature):
                candidates.update(idx.buckets.get(key, ()))
            for item_idx in candidates:
                other = idx.signatures[item_idx]
                if other is None:
                    continue
                est = hasher.estimate_jaccard(signature, other)
                doc_jaccard[item_idx] = est
                if est > best_jaccard.get(item_idx, 0.0):
                    best_jaccard[item_idx] = est

        # --- tier 4 material: keep the text behind strong signals ----------
        interesting = set(exact_hits) & {i for i in exact_hits if doc_id in exact_hits[i]}
        interesting |= {i for i, c in per_doc.items() if c >= EVIDENCE_MIN_13GRAMS}
        interesting |= {
            i for i, j in doc_jaccard.items() if j >= THRESHOLDS["minhash_suspect"]
        }
        for item_idx in interesting:
            if len(evidence[item_idx]) < evidence_cap:
                evidence[item_idx].append(
                    {
                        "split": split,
                        "train_id": doc_id,
                        "shared_13grams": per_doc.get(item_idx, 0),
                        "minhash_jaccard": round(doc_jaccard.get(item_idx, 0.0), 3),
                        "exact": doc_id in exact_hits.get(item_idx, []),
                        "train_prompt": prompt_text[:3000],
                        "train_response_head": resp_text[:600],
                    }
                )

        # --- response side (weaker signal, prompt-order n-grams only) ------
        if resp_text:
            for h in ngram_hashes(tokens(train_core(resp_text)), N_LONG):
                for pair in idx.long.get(h, ()):
                    hits_resp.add(pair)

    return {
        "split": split,
        "rows": rows,
        "hits_long": hits_long,
        "hits_short": hits_short,
        "hits_resp": hits_resp,
        "exact_hits": {k: v for k, v in exact_hits.items()},
        "best_jaccard": best_jaccard,
        "evidence": {k: v for k, v in evidence.items()},
    }


def build_tasks(sources: dict[str, str], limit_rows: int, evidence_cap: int) -> list[tuple]:
    tasks = []
    for split, path in sources.items():
        size = os.path.getsize(path)
        for start in range(0, size, CHUNK_BYTES):
            tasks.append(
                (split, path, start, min(start + CHUNK_BYTES, size), limit_rows, evidence_cap)
            )
    return tasks


